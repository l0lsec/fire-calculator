#!/usr/bin/env node
// Writes docs/VERIFICATION.md from the unlazy ledgers (.unlazy/fire-v1/gates/*.md)
// and GATES.md: every gate, its status, and its recorded evidence summary.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);

// The checker records absolute working directories in evidence; keep the
// tracked plan ledger free of local home paths (open-source hygiene).
{
  const gates = new URL("GATES.md", root);
  const text = readFileSync(gates, "utf8");
  const scrubbed = text.replace(/cwd=\/[^;]*?\/fire-calculator/g, "cwd=<repo>");
  if (scrubbed !== text) writeFileSync(gates, scrubbed);
}
const dir = new URL(".unlazy/fire-v1/gates/", root);
const files = [
  ...readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort((a, b) => a.localeCompare(b, "en", { numeric: true }))
    .map((f) => ({ id: f.replace(/\.md$/, ""), path: new URL(f, dir) })),
  { id: "plan", path: new URL("GATES.md", root) },
];

const rows = [];
for (const f of files) {
  const text = readFileSync(f.path, "utf8");
  const abandoned = new Map([...text.matchAll(/^ABANDON: (\S+) (.+)$/gm)].map((m) => [m[1], m[2]]));
  for (const m of text.matchAll(/^- \[([ x])\] (\S+): (.+)\n((?: {2}.+\n?)*)/gm)) {
    const body = m[4] ?? "";
    const evidence = /EVIDENCE: (.+)/.exec(body)?.[1] ?? "pending";
    const manual = !/CHECK:/.test(body);
    const met = m[1] === "x" && evidence !== "pending";
    const status = abandoned.has(m[2]) ? "abandoned" : met ? "met" : "unmet";
    const decisive = /output=(.*)$/.exec(evidence)?.[1] ?? evidence;
    rows.push({
      gate: `${f.id}:${m[2]}`,
      title: m[3].trim(),
      status,
      manual,
      note: abandoned.get(m[2]) ?? (status === "met" ? decisive.split(" | ").slice(-1)[0] : ""),
    });
  }
}

const count = (s) => rows.filter((r) => r.status === s).length;
const lines = [
  "# Verification record",
  "",
  `Generated by \`scripts/verification-report.mjs\` from the gate ledgers. ${rows.length} gates: ${count("met")} met, ${count("unmet")} unmet, ${count("abandoned")} abandoned.`,
  "",
  "A runnable gate is met only when its check exited 0 and printed its success token; a manual gate is met only with written evidence.",
  "",
  "| Gate | Status | Outcome | Evidence |",
  "|---|---|---|---|",
  ...rows.map(
    (r) =>
      `| ${r.gate} | ${r.status}${r.manual ? " (manual)" : ""} | ${r.title.replace(/\|/g, "/")} | ${String(r.note).replace(/\|/g, "/").slice(0, 80)} |`,
  ),
  "",
];
writeFileSync(new URL("docs/VERIFICATION.md", root), lines.join("\n"));
console.log(
  `docs/VERIFICATION.md: ${rows.length} gates, ${count("met")} met, ${count("unmet")} unmet, ${count("abandoned")} abandoned`,
);
